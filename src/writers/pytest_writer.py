import os
import re

from models import TestCase
from writers.base import Writer

HEADER = '''"""Auto-generated by api-test-forge. Do not hand-edit — regenerate instead.

Set API_BASE_URL before running, e.g.:
    API_BASE_URL=http://localhost:8000 pytest test_generated.py
"""

import os
import requests

BASE_URL = os.environ.get("API_BASE_URL", "http://localhost:8000")

'''


def _slugify(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")


def _render_case(case: TestCase, index: int) -> str:
    endpoint = case.endpoint
    path = endpoint.path
    for name, value in case.path_params.items():
        path = path.replace("{" + name + "}", str(value))

    fn_name = f"test_{_slugify(endpoint.method + '_' + endpoint.path)}_{case.category}_{index}"

    lines = [f"def {fn_name}():"]
    lines.append(f'    """{case.description}"""')
    lines.append(f'    url = BASE_URL + "{path}"')

    request_args = [f'"{endpoint.method.lower()}"', "url"]
    if case.query_params:
        lines.append(f"    params = {case.query_params!r}")
        request_args.append("params=params")
    if case.headers:
        lines.append(f"    headers = {case.headers!r}")
        request_args.append("headers=headers")
    if case.body is not None:
        lines.append(f"    body = {case.body!r}")
        request_args.append("json=body")

    lines.append(f"    response = requests.request({', '.join(request_args)})")

    if case.expected_status is not None:
        lines.append(f"    assert response.status_code == {case.expected_status}, response.text")
    else:
        lines.append("    # No specific status asserted — inspect manually.")
        lines.append("    assert response is not None")

    return "\n".join(lines) + "\n"


class PytestWriter(Writer):
    def write(self, cases: list[TestCase], out_dir: str) -> str:
        os.makedirs(out_dir, exist_ok=True)
        out_path = os.path.join(out_dir, "test_generated.py")

        body = HEADER
        for i, case in enumerate(cases):
            body += "\n" + _render_case(case, i) + "\n"

        with open(out_path, "w") as f:
            f.write(body)

        return out_path
